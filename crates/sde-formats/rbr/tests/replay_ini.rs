//! Tests for the replay metadata `.ini` parser.
//!
//! The two fixtures below are verbatim copies of the sidecars from
//! `.sample-data/RBR/MINI JCW - Gabiria-Legazpi 2004/` (gitignored, per
//! PROJECT_PLAN.md's convention of not committing capture data). They're
//! inlined rather than referenced so the suite is hermetic and runs
//! anywhere. `parses_real_sample_data_when_present` additionally exercises
//! the on-disk path against the real captures when they exist locally.

